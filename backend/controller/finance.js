const Finance = require('../models/finance');
const { generateRecordId } = require('../utils/autogeneratedid');
const asyncHandler = require('../utils/asyncHandler');

const createFinanceRecord = asyncHandler(async (req, res) => {
    const { societyId } = req.params;
    const { type, category, amount, description, date } = req.body;

    if (!type || !category || !amount || !description || !date) {
      return res.status(400).json({
        success: false,
        message: 'Please provide type, category, amount, description and date'
      });
    }

    if (type !== 'INCOME' && type !== 'EXPENSE') {
      return res.status(400).json({
        success: false,
        message: 'Type must be INCOME or EXPENSE'
      });
    }

    if (amount <= 0) {
      return res.status(400).json({
        success: false,
        message: 'Amount must be greater than 0'
      });
    }

    const recordId = await generateRecordId();

    const record = await Finance.create({
      society: societyId,
      type,
      category,
      amount,
      description,
      date,
      recordId,
      recordedBy: req.user._id
    });

    res.status(201).json({
      success: true,
      message: `${type} record created successfully`,
      record
    });

});

const getFinanceDashboard = asyncHandler(async (req, res) => {
    const { societyId } = req.params;

    const records = await Finance.find({ society: societyId })
      .populate('recordedBy', 'name userId')
      .sort({ date: -1 });

    let totalIncome = 0;
    let totalExpense = 0;

    for (const record of records) {
      if (record.type === 'INCOME') {
        totalIncome += record.amount;
      } else {
        totalExpense += record.amount;
      }
    }

    const balance = totalIncome - totalExpense;

    res.status(200).json({
      success: true,
      totalIncome,
      totalExpense,
      balance,
      recordCount: records.length,
      records
    });

});

module.exports = { createFinanceRecord, getFinanceDashboard };
