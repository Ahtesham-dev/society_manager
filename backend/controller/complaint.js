const Complaint = require('../models/complaint');
const Rule = require('../models/rulescreation');
const { generateComplaintId } = require('../utils/autogeneratedid');

// Flow: Validate → Check rule exists → Create complaint → Hide complainant by default

const submitComplaint = async (req, res) => {
  try {
    const { societyId } = req.params;
    const { reportedFlat, reportedUser, ruleId, description, evidence } = req.body;

    // STEP 1: Validate required fields
    if (!reportedFlat || !ruleId || !description) {
      return res.status(400).json({
        success: false,
        message: 'Please provide reportedFlat, ruleId and description'
      });
    }

    // STEP 2: Confirm the rule actually exists in this society
    const rule = await Rule.findOne({ _id: ruleId, society: societyId });
    if (!rule) {
      return res.status(404).json({
        success: false,
        message: 'Rule not found in this society'
      });
    }

    // STEP 3: Generate unique complaint ID
    const complaintId = await generateComplaintId();

    // STEP 4: Create the complaint
    const complaint = await Complaint.create({
      society: societyId,
      complainant: req.user._id,        // who is filing — stored but hidden by default
      reportedFlat: reportedFlat.trim(),
      reportedUser: reportedUser || undefined,
      rule: ruleId,
      description: description.trim(),
      evidence: evidence || [],
      complaintId,
      status: 'SUBMITTED'
    });

    res.status(201).json({
      success: true,
      message: 'Complaint submitted successfully',
      complaint
    });

  } catch (error) {
    console.error('Submit Complaint Error:', error);
    res.status(500).json({
      success: false,
      message: 'Server error while submitting complaint'
    });
  }
};

module.exports = { submitComplaint };