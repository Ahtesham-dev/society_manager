const Fine = require('../models/fine');
const User = require('../models/user');
const Complaint = require('../models/complaint');
const Rule = require('../models/rulescreation');
const { generateFineId } = require('../utils/autogeneratedid');
const { createAuditLog } = require('../utils/audit');
const asyncHandler = require('../utils/asyncHandler');

// Flow: Validate → Find resident → Verify complaint/rule (if given) → Create Fine

const createFine = asyncHandler(async (req, res) => {
    const { societyId } = req.params;
    const { residentUserId, flatNo, complaintId, ruleId, amount, reason, dueDate } = req.body;

    //Validate required fields
    if (!residentUserId || !flatNo || !amount || !reason || !dueDate) {
      return res.status(400).json({
        success: false,
        message: 'Please provide residentUserId, flatNo, amount, reason and dueDate'
      });
    }

    // Finding the resident using their custom userId
    const resident = await User.findOne({ userId: residentUserId });
    if (!resident) {
      return res.status(404).json({
        success: false,
        message: 'No user found with this userId'
      });
    }

    // If complaintId provided, verify it exists in this society
    let complaint = null;
    if (complaintId) {
      complaint = await Complaint.findOne({ _id: complaintId, society: societyId });
      if (!complaint) {
        return res.status(404).json({
          success: false,
          message: 'Complaint not found in this society'
        });
      }
    }

    // If ruleId provided, verify it exists in this society
    let rule = null;
    if (ruleId) {
      rule = await Rule.findOne({ _id: ruleId, society: societyId });
      if (!rule) {
        return res.status(404).json({
          success: false,
          message: 'Rule not found in this society'
        });
      }
    }

    // Validate amount is a positive number
    if (amount <= 0) {
      return res.status(400).json({
        success: false,
        message: 'Amount must be greater than 0'
      });
    }

    //Generating unique fine ID
    const fineId = await generateFineId();

    // Creating the fine
    const fine = await Fine.create({
      society: societyId,
      resident: resident._id,
      flatNo: flatNo.trim(),
      complaint: complaintId || undefined,
      rule: ruleId || undefined,
      amount,
      reason: reason.trim(),
      dueDate,
      fineId,
      status: 'PENDING',
      createdBy: req.user._id
    });

    await createAuditLog({
      society: societyId,
      performedBy: req.user._id,
      action: 'CREATE_FINE',
      targetType: 'Fine',
      targetId: fine._id,
      details: `Fined ₹${amount} to resident for: ${reason}`
    });

    res.status(201).json({
      success: true,
      message: `Fine of ₹${amount} created for ${resident.name}`,
      fine
    });

});

// Flow: Check for ?mine=true filter → Build query → Fetch → Populate → Return

const getAllFines = asyncHandler(async (req, res) => {
    const { societyId } = req.params;
    const { mine } = req.query;   // reads ?mine=true from URL

    // Base filter - always scoped to this society
    const filter = { society: societyId };

    // If frontend asks for "Only mine", add resident filter
    if (mine === 'true') {
      filter.resident = req.user._id;
    }

    const fines = await Fine.find(filter)
      .populate('resident', 'name userId')
      .populate('createdBy', 'name userId')
      .populate('verifiedBy', 'name userId')
      .populate('complaint', 'complaintId description')
      .populate('rule', 'ruleId title category')
      .sort({ createdAt: -1 });

    res.status(200).json({
      success: true,
      count: fines.length,
      fines
    });

});

// Flow: Find fine → Check ownership → Check status → Update → Save
const submitPayment = asyncHandler(async (req, res) => {
    const { societyId, fineId } = req.params;
    const { paymentProof } = req.body;

    //Validate payment proof was provided
    if (!paymentProof) {
      return res.status(400).json({
        success: false,
        message: 'Please provide payment proof (receipt/screenshot URL)'
      });
    }

    //Find the fine (of this society only )
    const fine = await Fine.findOne({
      _id: fineId,
      society: societyId
    });

    if (!fine) {
      return res.status(404).json({
        success: false,
        message: 'Fine not found in this society'
      });
    }

    //Ownership check - only the resident who owes this fine can pay it
    if (fine.resident.toString() !== req.user._id.toString()) {
      return res.status(403).json({
        success: false,
        message: 'You can only submit payment for your own fines'
      });
    }

    //Checking if current status allows payment submission
    if (fine.status !== 'PENDING') {
      return res.status(400).json({
        success: false,
        message: `Cannot submit payment. Fine status is currently ${fine.status}`
      });
    }

    //Update fine
    fine.paymentProof = paymentProof;
    fine.status = 'PAYMENT_SUBMITTED';
    await fine.save();

    res.status(200).json({
      success: true,
      message: 'Payment submitted. Waiting for Treasurer verification.',
      fine
    });

});

const verifyPayment = asyncHandler(async (req, res) => {
    const { societyId, fineId } = req.params;
    const { action } = req.body;

    if (!action || (action !== 'APPROVE' && action !== 'REJECT')) {
      return res.status(400).json({
        success: false,
        message: 'Please provide action as APPROVE or REJECT'
      });
    }

    const fine = await Fine.findOne({
      _id: fineId,
      society: societyId
    });

    if (!fine) {
      return res.status(404).json({
        success: false,
        message: 'Fine not found in this society'
      });
    }

    if (fine.status !== 'PENDING' && fine.status !== 'REJECTED') {
      return res.status(400).json({
        success: false,
        message: `Cannot submit payment. Fine status is currently ${fine.status}`
      });
    }


    if (action === 'APPROVE') {
      fine.status = 'PAID';
      fine.paidDate = Date.now();
    } else {
      fine.status = 'REJECTED';
    }

    fine.verifiedBy = req.user._id;
    await fine.save();

    await createAuditLog({
      society: societyId,
      performedBy: req.user._id,
      action: action === 'APPROVE' ? 'APPROVE_FINE_PAYMENT' : 'REJECT_FINE_PAYMENT',
      targetType: 'Fine',
      targetId: fine._id,
      details: `${action} payment for fine ${fine.fineId}`
    });

    res.status(200).json({
      success: true,
      message: action === 'APPROVE'
        ? 'Payment approved. Fine marked as PAID.'
        : 'Payment rejected. Resident can resubmit proof.',
      fine
    });

});

module.exports = { createFine, getAllFines, submitPayment, verifyPayment };
