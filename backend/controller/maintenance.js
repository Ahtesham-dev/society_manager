const Maintenance = require('../models/maintenance');
const Membership = require('../models/membership');
const { generateMaintenanceId } = require('../utils/autogeneratedid');

const createMonthlyDue = async (req, res) => {
  try {
    const { societyId } = req.params;
    const { month, amount, dueDate } = req.body;

    if (!month || !amount || !dueDate) {
      return res.status(400).json({
        success: false,
        message: 'Please provide month, amount and dueDate'
      });
    }

    if (amount <= 0) {
      return res.status(400).json({
        success: false,
        message: 'Amount must be greater than 0'
      });
    }

    const activeMembers = await Membership.find({
      society: societyId,
      status: 'ACTIVE'
    });

    if (activeMembers.length === 0) {
      return res.status(404).json({
        success: false,
        message: 'No active members found in this society'
      });
    }

    const createdDues = [];
    const skippedFlats = [];

    for (const member of activeMembers) {
      const alreadyExists = await Maintenance.findOne({
        society: societyId,
        resident: member.user,
        month: month
      });

      if (alreadyExists) {
        skippedFlats.push(member.flatNo);
        continue;
      }

      const maintenanceId = await generateMaintenanceId();

      const due = await Maintenance.create({
        society: societyId,
        resident: member.user,
        flatNo: member.flatNo,
        month: month,
        amount: amount,
        dueDate: dueDate,
        maintenanceId: maintenanceId,
        createdBy: req.user._id
      });

      createdDues.push(due);
    }

    res.status(201).json({
      success: true,
      message: `Created ${createdDues.length} due(s) for ${month}. Skipped ${skippedFlats.length} (already billed).`,
      createdCount: createdDues.length,
      skippedFlats: skippedFlats,
      dues: createdDues
    });

  } catch (error) {
    console.error('Create Monthly Due Error:', error);
    res.status(500).json({
      success: false,
      message: 'Server error while creating monthly dues'
    });
  }
};

module.exports = { createMonthlyDue };